function getTranslationText(key, langCode) {
    const lang = langCode || localStorage.getItem("cc_language") || "en";
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
}

window.getTranslationText = getTranslationText;

function translatePage(langCode) {
    const lang = langCode || localStorage.getItem("cc_language") || "en";
    localStorage.setItem("cc_language", lang);

    const langSelects = document.querySelectorAll(".topbar-lang-select, #settingLanguageSelect, #settingDashboardLangSelect");
    langSelects.forEach(select => {
        if (select) select.value = lang;
    });

    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

    // 1. Text elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    // 2. Input placeholders with data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key]) {
            el.setAttribute("placeholder", dict[key]);
        }
    });

    // 3. Dynamic Welcome Header
    const welcomeHeader = document.getElementById("welcomeHeaderTitle");
    if (welcomeHeader) {
        const userNameEl = document.getElementById("welcomeUserName");
        const userName = userNameEl ? userNameEl.textContent : (welcomeHeader.getAttribute("data-user-name") || "Admin");
        welcomeHeader.innerHTML = `${dict.welcome_back}, <span id="welcomeUserName">${userName}</span> 👋`;
    }

    // 4. Search placeholders
    const searchInputs = document.querySelectorAll("#topbarSearchInput, #dashboardSearch, input[type='search'], .topbar-search-box input, .topbar-search-input");
    searchInputs.forEach(input => {
        if (input) input.setAttribute("placeholder", dict.search_placeholder);
    });

    // 5. Back to Dashboard links
    document.querySelectorAll(".back-dashboard-btn, a[href*='admin.html']").forEach(btn => {
        if (btn.classList.contains("back-dashboard-btn") || (btn.innerText && btn.innerText.includes("Back to Dashboard"))) {
            btn.innerHTML = `<i class="fa-solid fa-arrow-left me-1"></i> ${dict.back_to_dashboard}`;
        }
    });

    // 6. Re-trigger dynamic JS UI update functions if defined
    if (typeof window.updateDynamicStatsUI === "function") {
        window.updateDynamicStatsUI();
    }
}

window.translatePage = translatePage;

document.addEventListener("DOMContentLoaded", () => {
    translatePage();
});
